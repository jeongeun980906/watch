"""Precompute T5 text embeddings for the EgoVerse retrieval configs.

The command space is small and fixed: 8 activity classes × 5 embodiment tags
(``[aria]/[scale]/[MECKA]/[eva]/[human]``) = 40 strings, generated by
``_commands_with_tags()`` in egoverse_ret_dataset.py.

Output: ``<out_dir>/t5_embeddings.pkl``  (dict[str, (1,512,1024) bf16 tensor])

Usage:
    <python> -m cosmos_policy.datasets.save_egoverse_t5_text_embeddings \\
        --out_dir /mnt/ddn/dataset/egoverse_pairs_v5
"""
from __future__ import annotations

import argparse

from cosmos_policy.datasets.egoverse_ret_dataset import _commands_with_tags
from cosmos_policy.datasets.t5_embedding_utils import (
    generate_t5_embeddings,
    save_embeddings,
)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out_dir", type=str, default="/mnt/ddn/dataset/egoverse_pairs_v5")
    args = ap.parse_args()

    commands = _commands_with_tags()
    print(f"Embedding {len(commands)} command strings:")
    for c in commands:
        print(f"  - {c!r}")

    embs = generate_t5_embeddings(commands)
    path = save_embeddings(embs, args.out_dir)
    print(f"saved {len(embs)} embeddings -> {path}")


if __name__ == "__main__":
    main()
